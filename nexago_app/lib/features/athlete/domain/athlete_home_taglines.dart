/// Frase do topo da Início, sob o nome do atleta: uma piada do esporte
/// principal do perfil, no lugar do antigo "O esporte conecta.".
///
/// Troca uma vez por dia (o hero redesenha o tempo todo; sortear a cada build
/// faria a frase pular na tela) e [seed] — o uid — desloca a lista, para dois
/// atletas do mesmo esporte não verem a mesma frase no mesmo dia. Esporte sem
/// lista própria, ou nulo, cai nas frases gerais.
String athleteHomeTaglineFor({
  String? sport,
  required DateTime now,
  String seed = '',
}) {
  final code = SportCatalog.profileCodeOf(sport);
  final phrases = athleteHomeTaglines[code] ?? athleteHomeTaglines['OUTROS']!;
  final day = DateTime.utc(now.year, now.month, now.day)
      .difference(DateTime.utc(2026))
      .inDays;
  final offset = seed.codeUnits.fold<int>(0, (sum, unit) => sum + unit);
  return phrases[(day + offset) % phrases.length];
}

